class KNNClassifier():
  def fit(self,X,y):
    self.X=X
    self.y=y

  def predict(self,X,K,epsilon=1e-3):
    N=len(X)
    y_hat=np.zeros(N)

    for i in range(N):
      dist2 = np.sum((self.X-X[i])**2, axis=1)
      idxt = np.argsort(dist2)[:K]
      # Ensure idxt values are within the range
      idxt = idxt[idxt < len(self.y)]
      gamma_k = 1/(np.sqrt(dist2[idxt]+epsilon))
      if len(idxt) > 0:
        y_hat[i] =np.bincount(self.y[idxt],weights =gamma_k).argmax()
    return y_hat

