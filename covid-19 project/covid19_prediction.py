from scipy.stats import multivariate_normal as mvn

class GaussNB():
  def fit(self,X,y,epsilon=1e-3):
    self.likelihoods=dict()
    self.priors=dict()#prior for each class
    self.K=set(y.astype(int)) #for classification of unique values object 0 and 1

    for k in self.K:
      X_k=X[y==k,:]
      cov_matrix = np.cov(X_k, rowvar=False) + np.eye(X_k.shape[1]) * epsilon
      self.likelihoods[k]={"mean": X_k.mean(axis=0),"cov": cov_matrix}
      self.priors[k]=len(X_k)/len(X)

  def predict(self,X):
    N,D=X.shape
    P_hat=np.zeros((N,len(self.K)))

    for k,l in self.likelihoods.items():
      P_hat[:,k]=mvn.logpdf(X,l["mean"],l["cov"]+np.log(self.priors[k]))
    return P_hat.argmax(axis=1)

def accuracy(y,y_hat):
  return np.mean(y==y_hat)

